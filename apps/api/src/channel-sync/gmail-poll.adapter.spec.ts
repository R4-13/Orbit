import type { InboundEmail } from '@orbit/integration-core';
import { GmailPollAdapter } from './gmail-poll.adapter';
import { GmailConnectorService } from '../integrations/gmail-connector.service';
import { PrismaService } from '../prisma/prisma.service';

function email(overrides: Partial<InboundEmail> = {}): InboundEmail {
  return {
    providerMessageId: 'msg-1',
    from: 'kunde@example.com',
    to: ['vertrieb@firma.example'],
    subject: 'Anfrage',
    bodyText: 'Wir haben Interesse.',
    receivedAt: new Date('2026-10-04T08:00:00Z'),
    attachments: [],
    ...overrides,
  };
}

/** Bildet `GmailConnectorService.listMessageIdsSince` nach: neueste zuerst, bis zur Marke (nicht enthalten) oder höchstens `maxTotal`, mit Rand. */
function listSince(ids: string[]) {
  return async (_tenantId: string, stopBefore: string | null, maxTotal: number) => {
    const out: string[] = [];
    let markFound = false;
    for (const id of ids) {
      if (stopBefore !== null && id === stopBefore) {
        markFound = true;
        break;
      }
      out.push(id);
      if (out.length > maxTotal) break;
    }
    const boundary = out.length > maxTotal ? (out.pop() ?? null) : null;
    return { ids: out, boundary, markFound };
  };
}

describe('GmailPollAdapter', () => {
  function buildAdapter(emails: InboundEmail[], connectedAddress: string | null = 'konto@firma.example', options: { ids?: string[]; known?: string[] } = {}) {
    const ids = options.ids ?? emails.map((e) => e.providerMessageId);
    const gmailConnector = { listMessageIdsSince: jest.fn(listSince(ids)), fetchMessages: jest.fn().mockResolvedValue(emails) } as unknown as GmailConnectorService;
    const prisma = {
      forTenantId: jest.fn().mockReturnValue({
        integration: { findUnique: jest.fn().mockResolvedValue(connectedAddress ? { externalAccountId: connectedAddress } : null) },
        intakeEvent: { findMany: jest.fn().mockResolvedValue((options.known ?? []).map((externalEventId) => ({ externalEventId }))) },
      }),
    } as unknown as PrismaService;
    return { adapter: new GmailPollAdapter(gmailConnector, prisma), gmailConnector };
  }

  it('translates InboundEmail[] into NormalizedIntakeEvent[] with the EMAIL/gmail channel tagging, thread data and the given connectionId', async () => {
    const { adapter } = buildAdapter([
      email({ threadId: 'thread-9', rfcMessageId: '<a@x>', inReplyTo: '<b@x>', references: ['<b@x>'], autoGenerated: false, bulk: false }),
    ]);

    const result = await adapter.poll('tenant_1', 'connection_1', null);

    expect(result.events).toEqual([
      {
        tenantId: 'tenant_1',
        connectionId: 'connection_1',
        channel: 'EMAIL',
        provider: 'gmail',
        externalEventId: 'msg-1',
        occurredAt: new Date('2026-10-04T08:00:00Z'),
        sender: { address: 'kunde@example.com' },
        recipients: [{ address: 'vertrieb@firma.example' }],
        subject: 'Anfrage',
        content: 'Wir haben Interesse.',
        attachments: [],
        threadId: 'thread-9',
        rfcMessageId: '<a@x>',
        inReplyTo: '<b@x>',
        references: ['<b@x>'],
        direction: 'INBOUND',
        hints: { autoGenerated: false, bulk: false, providerSpam: false },
      },
    ]);
  });

  it('marks a message from the connected mailbox itself as OUTBOUND (derived from the Integration, never hardcoded) and a SENT-labelled one too', async () => {
    const { adapter } = buildAdapter([
      email({ providerMessageId: 'own', from: 'Konto@Firma.example' }),
      email({ providerMessageId: 'sent', from: 'someone-else@example.com', labelIds: ['SENT'] }),
      email({ providerMessageId: 'customer' }),
    ]);

    const result = await adapter.poll('tenant_1', 'connection_1', null);

    expect(result.events.map((e) => [e.externalEventId, e.direction])).toEqual([
      ['own', 'OUTBOUND'],
      ['sent', 'OUTBOUND'],
      ['customer', 'INBOUND'],
    ]);
  });

  it('passes deterministic header hints and the provider SPAM label through as hints, not as a decision', async () => {
    const { adapter } = buildAdapter([email({ autoGenerated: true, bulk: true, labelIds: ['SPAM'] })]);

    const result = await adapter.poll('tenant_1', 'connection_1', null);

    expect(result.events[0]?.hints).toEqual({ autoGenerated: true, bulk: true, providerSpam: true });
  });

  it('liest die Kennungen des Mandanten; ein alter Marker ohne Fortschritt (nur eine Kennung) zählt wie ein erster Abruf', async () => {
    const { adapter, gmailConnector } = buildAdapter([]);

    await adapter.poll('tenant_2', 'connection_2', 'some-previous-cursor');

    expect(gmailConnector.listMessageIdsSince).toHaveBeenCalledWith('tenant_2', null, expect.any(Number)); // ein früherer Marker ohne Fortschritt zählt wie ein erster Abruf
    expect(gmailConnector.fetchMessages).not.toHaveBeenCalled(); // nichts Neues: nichts wird geholt
  });

  it('holt nur noch unbekannte Nachrichten – auch wenn zwischen zwei Takten mehr als zehn eintrafen (Messlauf 21.10.: drei Eingänge gingen verloren)', async () => {
    const ids = Array.from({ length: 14 }, (_, i) => `m${14 - i}`); // neueste zuerst: m14 … m1
    const { adapter, gmailConnector } = buildAdapter([email({ providerMessageId: 'm1' })], 'konto@firma.example', { ids, known: ['m14', 'm13', 'm12'] });

    await adapter.poll('tenant_5', 'connection_5', 'm14');

    const asked = (gmailConnector.fetchMessages as jest.Mock).mock.calls[0]![1] as string[];
    expect(asked).toHaveLength(11); // alle bekannten sind ausgelassen, die elf unbekannten (m11 … m1) werden geholt
    expect(asked[0]).toBe('m1'); // die ältesten zuerst
    expect(asked.at(-1)).toBe('m11');
    expect(asked).not.toContain('m12');
  });

  it('ein großer Rückstand wird je Takt in einer begrenzten Menge abgearbeitet, die ältesten zuerst', async () => {
    const ids = Array.from({ length: 80 }, (_, i) => `n${80 - i}`);
    const { adapter, gmailConnector } = buildAdapter([], 'konto@firma.example', { ids });

    await adapter.poll('tenant_6', 'connection_6', null);

    const asked = (gmailConnector.fetchMessages as jest.Mock).mock.calls[0]![1] as string[];
    expect(asked).toHaveLength(25);
    expect(asked[0]).toBe('n1');
  });

  it('rückt die Marke auf die neueste gesehene Nachricht, wenn nichts mehr offen ist, und behält sie bei leerem Postfach', async () => {
    const { adapter: adapterWithResults } = buildAdapter([email({ providerMessageId: 'newest-msg' })]);
    expect(JSON.parse((await adapterWithResults.poll('tenant_3', 'connection_3', null)).nextCursor ?? '')).toEqual({ v: 1, mark: 'newest-msg' });

    const { adapter: adapterEmpty } = buildAdapter([]);
    expect((await adapterEmpty.poll('tenant_3', 'connection_3', 'old-cursor')).nextCursor).toBe('old-cursor');
  });
});

/**
 * Rückstand weit über dem Fenster (Funktionsnachweis 23.10.): ein Nachbau von Postfach + Eingangsdatenbank, über den der Adapter wiederholt abgefragt wird – mit Unterbrechungen. Es wird nichts versendet.
 */
describe('GmailPollAdapter – Rückstand über das Fenster hinaus', () => {
  function world(total: number) {
    // neueste zuerst
    const mailbox: string[] = Array.from({ length: total }, (_, i) => `g${String(total - i).padStart(4, '0')}`);
    const taken = new Map<string, number>(); // Kennung → wie oft aufgenommen
    const gmailConnector = {
      listMessageIdsSince: jest.fn((tenantId: string, stop: string | null, max: number) => listSince(mailbox)(tenantId, stop, max)),
      fetchMessages: jest.fn(async (_t: string, ids: readonly string[]) => ids.map((id) => email({ providerMessageId: id }))),
    } as unknown as GmailConnectorService;
    const prisma = {
      forTenantId: jest.fn().mockReturnValue({
        integration: { findUnique: jest.fn().mockResolvedValue({ externalAccountId: 'konto@firma.example' }) },
        intakeEvent: {
          findMany: jest.fn(async ({ where }: { where: { externalEventId: { in: string[] } } }) => where.externalEventId.in.filter((id) => taken.has(id)).map((externalEventId) => ({ externalEventId }))),
        },
      }),
    } as unknown as PrismaService;
    const adapter = new GmailPollAdapter(gmailConnector, prisma);
    /** Ein Takt wie im Worker: abrufen, aufnehmen (idempotent), Marke übernehmen – außer der Takt wird „unterbrochen“. */
    async function tick(cursor: string | null, options: { crashAfterPoll?: boolean; crashAfterTaking?: number } = {}) {
      const { events, nextCursor } = await adapter.poll('t', 'c', cursor);
      if (options.crashAfterPoll) return { cursor, events: events.length };
      const take = options.crashAfterTaking ?? events.length;
      events.slice(0, take).forEach((e) => taken.set(e.externalEventId, (taken.get(e.externalEventId) ?? 0) + 1));
      if (options.crashAfterTaking !== undefined) return { cursor, events: take }; // abgestürzt, bevor die Marke gespeichert wurde
      return { cursor: nextCursor, events: events.length };
    }
    return { mailbox, taken, tick, gmailConnector };
  }

  async function drain(w: ReturnType<typeof world>, start: string | null): Promise<string | null> {
    let cursor = start;
    for (let ticks = 0; ticks < 200; ticks += 1) {
      const r = await w.tick(cursor);
      cursor = r.cursor;
      if (r.events === 0) break;
    }
    return cursor;
  }

  it('erster Abruf bei großem Bestand: der Umfang sind die neuesten 200; sie werden vollständig, jede genau einmal, aufgenommen', async () => {
    const w = world(530);
    await drain(w, null);
    expect(w.taken.size).toBe(200);
    expect([...w.taken.values()].every((n) => n === 1)).toBe(true);
  });

  it('nach einer Unterbrechung (Marke stand bei einer früheren Nachricht, inzwischen kamen 230 neue, mehr als 200): alle werden aufgenommen – nicht nur die neuesten 200', async () => {
    const w = world(530);
    for (const id of w.mailbox.filter((m) => m <= 'g0300')) w.taken.set(id, 1);
    const cursor = await drain(w, JSON.stringify({ v: 1, mark: 'g0300' }));
    const newOnes = w.mailbox.filter((m) => m > 'g0300');
    expect(newOnes).toHaveLength(230);
    expect(newOnes.every((id) => w.taken.get(id) === 1)).toBe(true); // vollständig und genau einmal
    expect(JSON.parse(cursor ?? '').mark).toBe('g0530'); // erst jetzt rückt die Marke auf die neueste
  });

  it('die Marke bleibt stehen, solange Rückstand übrig ist', async () => {
    const w = world(530);
    for (const id of w.mailbox.filter((m) => m <= 'g0300')) w.taken.set(id, 1);
    const start = JSON.stringify({ v: 1, mark: 'g0300' });
    const first = await w.tick(start);
    expect(first.events).toBe(25);
    expect(first.cursor).toBe(start); // 205 sind noch offen
  });

  it('Unterbrechung nach dem Abruf (nichts aufgenommen) oder mitten in der Aufnahme: der nächste Takt holt nach, ohne Doppelungen', async () => {
    const w = world(260);
    for (const id of w.mailbox.filter((m) => m <= 'g0100')) w.taken.set(id, 1);
    let cursor: string | null = JSON.stringify({ v: 1, mark: 'g0100' });
    cursor = (await w.tick(cursor, { crashAfterPoll: true })).cursor;
    cursor = (await w.tick(cursor, { crashAfterTaking: 10 })).cursor; // 10 aufgenommen, Marke nicht gespeichert
    await drain(w, cursor);
    expect(w.mailbox.filter((m) => m > 'g0100').every((id) => w.taken.get(id) === 1)).toBe(true);
  });

  it('wiederholtes Abfragen ohne neue Nachrichten ändert nichts (keine zusätzlichen Wirkungen)', async () => {
    const w = world(50);
    const cursor = await drain(w, null);
    const afterDrain = [...w.taken.entries()];
    expect(afterDrain).toHaveLength(50);
    for (let i = 0; i < 5; i += 1) expect((await w.tick(cursor)).events).toBe(0);
    expect([...w.taken.entries()]).toEqual(afterDrain);
  });

  it('beim ersten Abruf mit großem Bestand wird der Rand des Fensters zur Marke, damit neue Nachrichten den Umfang nicht verschieben', async () => {
    const w = world(300);
    const first = await w.tick(null);
    expect(first.events).toBe(25);
    expect(JSON.parse(first.cursor ?? '')).toEqual({ v: 1, mark: 'g0100' }); // Fenster = g0300 … g0101; g0100 ist die erste nicht mehr enthaltene
  });

  it('eine gelöschte Marke wird nicht gefunden: Bekanntes wird nicht ein zweites Mal aufgenommen, und die Marke steht danach wieder auf einer vorhandenen Nachricht', async () => {
    const w = world(40);
    for (const id of w.mailbox) w.taken.set(id, 1);
    const r = await w.tick(JSON.stringify({ v: 1, mark: 'geloescht' }));
    expect(r.events).toBe(0);
    expect(JSON.parse(r.cursor ?? '').mark).toBe('g0040');
  });
});
