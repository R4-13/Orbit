import { createHash } from 'node:crypto';

/**
 * Qualitätsmessung der KI-Einstufung (BPF-05): reine Bewertungslogik, ohne Datenbank und ohne Modellaufruf – deshalb offline testbar. Der Lauf selbst (mit dem echten Modell)
 * steht in `scripts/run-ai-evaluation.ts`. Gemessen wird nicht nur „stimmt es“, sondern gerade das, was im Betrieb weh tut: übersehene Notfälle, Fehlalarme, zu Unrecht
 * ausgeschlossene Kundennachrichten und schwankende Antworten.
 */

export type RelevanceExpectation = 'BUSINESS_ACTIONABLE' | 'NOT_BUSINESS' | 'REVIEW' | 'NOT_BUSINESS_OR_REVIEW' | 'BUSINESS_OR_REVIEW';
export type UrgencyExpectation = 'CRITICAL' | 'HIGH_OR_CRITICAL' | 'NOT_CRITICAL';

export interface Expectation {
  relevance: RelevanceExpectation;
  categories?: string[];
  flags?: string[];
  multipleIntents?: boolean;
  urgency?: UrgencyExpectation;
  relation?: 'NEW' | 'CONTINUATION';
}

export interface EvaluationCase {
  id: string;
  label: string;
  from: string;
  subject: string;
  body: string;
  hints?: { autoGenerated?: boolean };
  expect: Expectation;
}

/** Was die Einstufung für einen Fall ergeben hat (nach den deterministischen Schwellen des Eingangs). */
export interface Observation {
  appliedRelevance: 'BUSINESS_ACTIONABLE' | 'NON_ACTIONABLE' | 'PRIVATE_PERSONAL' | 'UNKNOWN_REQUIRES_REVIEW';
  category: string;
  urgency: string;
  relation: string;
  riskFlags: string[];
  intentCount: number;
  latencyMs: number;
}

export interface CaseChecks {
  relevance: boolean;
  category?: boolean;
  urgency?: boolean;
  relation?: boolean;
  flags?: boolean;
  multipleIntents?: boolean;
}

export function relevanceOk(applied: Observation['appliedRelevance'], expected: RelevanceExpectation): boolean {
  switch (expected) {
    case 'BUSINESS_ACTIONABLE':
      return applied === 'BUSINESS_ACTIONABLE';
    case 'NOT_BUSINESS':
      return applied === 'NON_ACTIONABLE' || applied === 'PRIVATE_PERSONAL';
    case 'REVIEW':
      return applied === 'UNKNOWN_REQUIRES_REVIEW';
    case 'BUSINESS_OR_REVIEW':
      return applied === 'BUSINESS_ACTIONABLE' || applied === 'UNKNOWN_REQUIRES_REVIEW';
    default:
      return applied !== 'BUSINESS_ACTIONABLE';
  }
}

export function urgencyOk(urgency: string, expected: UrgencyExpectation): boolean {
  if (expected === 'CRITICAL') return urgency === 'CRITICAL';
  if (expected === 'HIGH_OR_CRITICAL') return urgency === 'CRITICAL' || urgency === 'HIGH';
  return urgency !== 'CRITICAL';
}

/** Nur was der Fall erwartet, wird geprüft – nicht erwartete Dimensionen bleiben `undefined` und zählen in keiner Quote. */
export function scoreCase(expect: Expectation, observed: Observation): { checks: CaseChecks; pass: boolean } {
  const checks: CaseChecks = {
    relevance: relevanceOk(observed.appliedRelevance, expect.relevance),
    ...(expect.categories ? { category: expect.categories.includes(observed.category) } : {}),
    ...(expect.urgency ? { urgency: urgencyOk(observed.urgency, expect.urgency) } : {}),
    ...(expect.relation ? { relation: observed.relation === expect.relation } : {}),
    ...(expect.flags ? { flags: expect.flags.every((f) => observed.riskFlags.includes(f)) } : {}),
    ...(expect.multipleIntents !== undefined ? { multipleIntents: observed.intentCount > 1 === expect.multipleIntents } : {}),
  };
  return { checks, pass: Object.values(checks).every((v) => v !== false) };
}

export interface CaseResult {
  id: string;
  label: string;
  expect: Expectation;
  /** Alle Wiederholungen dieses Falls. */
  runs: Array<{ observed?: Observation; error?: string; checks?: CaseChecks; pass: boolean }>;
}

export interface Metrics {
  cases: number;
  runs: number;
  /** Anteil bestandener Läufe (alle Wiederholungen). */
  passRate: number;
  /** Anteil je geprüfter Dimension. */
  accuracy: Record<string, { checked: number; ok: number; rate: number }>;
  /** Von allen Fällen, die ein Notfall (CRITICAL) sind: wie viele wurden als CRITICAL erkannt? `null`, wenn der Satz keine enthält. */
  emergencyRecall: number | null;
  /** Von allen Fällen, die kein Notfall sind: wie viele wurden fälschlich als CRITICAL eingestuft? */
  falseAlarmRate: number | null;
  /** Von allen geschäftlichen Fällen (erwartet BUSINESS_ACTIONABLE oder BUSINESS_OR_REVIEW): wie viele wurden zu Unrecht als „kein Geschäft“ ausgeschlossen? Schlimmster Fehler: die Kundin hört nie etwas. */
  missedBusinessRate: number | null;
  /** Anteil der Fälle, deren Wiederholungen dieselbe Kategorie, Relevanz und Dringlichkeit ergaben (nur bei mehr als einer Wiederholung aussagekräftig). */
  consistency: number | null;
  /**
   * Wie `consistency`, aber nur nach dem, was den Weg bestimmt: Prozessgruppe (Verkauf / Finanzen / sonstige), Relevanz und „Notfall ja/nein“. Unterschiede wie NORMAL gegen LOW
   * oder REQUEST_FOR_QUOTE gegen SALES_INQUIRY ändern den Weg nicht. Nur zur Information, nicht Teil der Gütekriterien.
   */
  routingConsistency: number | null;
  failedRuns: number;
  latencyMs: { p50: number; p95: number } | null;
}

/** Die Prozessgruppe, in die eine Kategorie führt (siehe `routeForCategory` im Eingang). */
export function routeGroup(category: string): 'SALES' | 'FINANCE' | 'OTHER' {
  return category === 'REQUEST_FOR_QUOTE' || category === 'SALES_INQUIRY' ? 'SALES' : category === 'INVOICE_RECEIVED' ? 'FINANCE' : 'OTHER';
}

const rate = (ok: number, total: number): number => (total === 0 ? 1 : ok / total);

export function percentile(values: readonly number[], p: number): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.max(0, Math.ceil((p / 100) * sorted.length) - 1))] as number;
}

export function aggregate(results: readonly CaseResult[]): Metrics {
  const runs = results.flatMap((r) => r.runs.map((run) => ({ case: r, run })));
  const accuracy: Metrics['accuracy'] = {};
  const tally = (name: string, ok: boolean) => {
    const entry = (accuracy[name] ??= { checked: 0, ok: 0, rate: 0 });
    entry.checked += 1;
    if (ok) entry.ok += 1;
  };
  let emergencies = 0;
  let emergenciesFound = 0;
  let nonEmergencies = 0;
  let falseAlarms = 0;
  let business = 0;
  let missed = 0;
  for (const { case: c, run } of runs) {
    if (!run.checks || !run.observed) continue;
    for (const [name, ok] of Object.entries(run.checks)) if (ok !== undefined) tally(name, ok);
    if (c.expect.urgency === 'CRITICAL') {
      emergencies += 1;
      if (run.observed.urgency === 'CRITICAL') emergenciesFound += 1;
    } else if (c.expect.urgency === 'NOT_CRITICAL') {
      nonEmergencies += 1;
      if (run.observed.urgency === 'CRITICAL') falseAlarms += 1;
    }
    if (c.expect.relevance === 'BUSINESS_ACTIONABLE' || c.expect.relevance === 'BUSINESS_OR_REVIEW') {
      business += 1;
      if (run.observed.appliedRelevance === 'NON_ACTIONABLE' || run.observed.appliedRelevance === 'PRIVATE_PERSONAL') missed += 1;
    }
  }
  for (const entry of Object.values(accuracy)) entry.rate = rate(entry.ok, entry.checked);

  const repeated = results.filter((r) => r.runs.filter((x) => x.observed).length > 1);
  const consistent = repeated.filter((r) => new Set(r.runs.filter((x) => x.observed).map((x) => `${x.observed!.category}|${x.observed!.appliedRelevance}|${x.observed!.urgency}`)).size === 1);
  const routingStable = repeated.filter((r) => new Set(r.runs.filter((x) => x.observed).map((x) => `${routeGroup(x.observed!.category)}|${x.observed!.appliedRelevance}|${x.observed!.urgency === 'CRITICAL'}`)).size === 1);
  const latencies = runs.flatMap(({ run }) => (run.observed ? [run.observed.latencyMs] : []));
  return {
    cases: results.length,
    runs: runs.length,
    passRate: rate(runs.filter(({ run }) => run.pass).length, runs.length),
    accuracy,
    emergencyRecall: emergencies === 0 ? null : emergenciesFound / emergencies,
    falseAlarmRate: nonEmergencies === 0 ? null : falseAlarms / nonEmergencies,
    missedBusinessRate: business === 0 ? null : missed / business,
    consistency: repeated.length === 0 ? null : consistent.length / repeated.length,
    routingConsistency: repeated.length === 0 ? null : routingStable.length / repeated.length,
    failedRuns: runs.filter(({ run }) => run.error).length,
    latencyMs: latencies.length === 0 ? null : { p50: percentile(latencies, 50), p95: percentile(latencies, 95) },
  };
}

export interface Thresholds {
  minPassRate: number;
  minEmergencyRecall: number;
  maxFalseAlarmRate: number;
  maxMissedBusinessRate: number;
  minConsistency: number;
  maxFailedRuns: number;
}

export interface ThresholdVerdict {
  ok: boolean;
  failures: string[];
}

/** Die Gütekriterien (`fixtures/evaluation/thresholds.json`): ein Lauf besteht nur, wenn jede erfüllt ist; fehlende Messwerte (z. B. keine Wiederholungen) zählen nicht. */
export function checkThresholds(metrics: Metrics, thresholds: Thresholds): ThresholdVerdict {
  const failures: string[] = [];
  const pct = (v: number) => `${(v * 100).toFixed(1)} %`;
  if (metrics.passRate < thresholds.minPassRate) failures.push(`Trefferquote ${pct(metrics.passRate)} < ${pct(thresholds.minPassRate)}`);
  if (metrics.emergencyRecall !== null && metrics.emergencyRecall < thresholds.minEmergencyRecall) failures.push(`Notfälle erkannt ${pct(metrics.emergencyRecall)} < ${pct(thresholds.minEmergencyRecall)}`);
  if (metrics.falseAlarmRate !== null && metrics.falseAlarmRate > thresholds.maxFalseAlarmRate) failures.push(`Fehlalarme ${pct(metrics.falseAlarmRate)} > ${pct(thresholds.maxFalseAlarmRate)}`);
  if (metrics.missedBusinessRate !== null && metrics.missedBusinessRate > thresholds.maxMissedBusinessRate) failures.push(`Zu Unrecht ausgeschlossene Kundennachrichten ${pct(metrics.missedBusinessRate)} > ${pct(thresholds.maxMissedBusinessRate)}`);
  if (metrics.consistency !== null && metrics.consistency < thresholds.minConsistency) failures.push(`Konsistenz ${pct(metrics.consistency)} < ${pct(thresholds.minConsistency)}`);
  if (metrics.failedRuns > thresholds.maxFailedRuns) failures.push(`${metrics.failedRuns} Läufe ohne Ergebnis > ${thresholds.maxFailedRuns}`);
  return { ok: failures.length === 0, failures };
}

/** Vergleich mit einem früheren Lauf: alles, was sich um mehr als `tolerance` (Anteil) verschlechtert hat. */
export function regressions(current: Metrics, baseline: Metrics, tolerance = 0.05): string[] {
  const out: string[] = [];
  const worse = (name: string, now: number | null, before: number | null, higherIsBetter: boolean) => {
    if (now === null || before === null) return;
    const delta = higherIsBetter ? before - now : now - before;
    if (delta > tolerance) out.push(`${name}: ${(before * 100).toFixed(1)} % → ${(now * 100).toFixed(1)} %`);
  };
  worse('Trefferquote', current.passRate, baseline.passRate, true);
  worse('Notfälle erkannt', current.emergencyRecall, baseline.emergencyRecall, true);
  worse('Fehlalarme', current.falseAlarmRate, baseline.falseAlarmRate, false);
  worse('Zu Unrecht ausgeschlossen', current.missedBusinessRate, baseline.missedBusinessRate, false);
  worse('Konsistenz', current.consistency, baseline.consistency, true);
  worse('Konsistenz des Wegs', current.routingConsistency, baseline.routingConsistency, true);
  return out;
}

/** SHA-256 des Prüfsatzes (Zeilenenden normalisiert) – zeigt, ob der versiegelte Satz nach dem ersten Lauf verändert wurde. */
export function sealOf(fileText: string): string {
  return createHash('sha256').update(fileText.replace(/\r\n/g, '\n'), 'utf8').digest('hex');
}

/** Strukturprüfung eines Katalogs: eindeutige Kennungen, vollständige Fälle, erkennbare Erwartung. */
export function catalogueProblems(cases: readonly EvaluationCase[]): string[] {
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const c of cases) {
    if (seen.has(c.id)) problems.push(`${c.id}: Kennung doppelt`);
    seen.add(c.id);
    if (!c.subject.trim() || !c.body.trim()) problems.push(`${c.id}: Betreff oder Text leer`);
    if (!/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(c.from)) problems.push(`${c.id}: Absenderadresse ungültig`);
    if (!c.expect?.relevance) problems.push(`${c.id}: Erwartung zur Relevanz fehlt`);
  }
  return problems;
}
