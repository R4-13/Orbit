/**
 * Live evaluation of the semantic triage against the separate catalogue (Amendment 02 §25.3). It calls the SAME
 * SemanticTriageService the intake uses, with the platform provider from the environment, and applies the SAME deterministic
 * thresholds — but it changes nothing: no intake event, no case, no mail, no task. Prints a table and writes a JSON report.
 *
 *   set -a && source .env && source .env.llm.local && set +a
 *   pnpm --filter @orbit/api exec ts-node scripts/run-triage-evaluation.ts <tenant-slug> [report.json]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { NestFactory } from '@nestjs/core';
import { deriveAppliedRelevance } from '../src/intake/triage-decision';
import { SemanticTriageService } from '../src/intake/semantic-triage.service';
import { AppModule } from '../src/app.module';
import { ORBIT_ENV } from '../src/config/env.token';
import { PrismaService } from '../src/prisma/prisma.service';
import type { OrbitEnv } from '@orbit/config';

interface Expectation {
  relevance: 'BUSINESS_ACTIONABLE' | 'NOT_BUSINESS' | 'REVIEW' | 'NOT_BUSINESS_OR_REVIEW';
  categories?: string[];
  flags?: string[];
  multipleIntents?: boolean;
}
interface CatalogueCase {
  id: string;
  label: string;
  from: string;
  subject: string;
  body: string;
  hints?: { autoGenerated?: boolean };
  expect: Expectation;
}

function relevanceOk(applied: string, expected: Expectation['relevance']): boolean {
  if (expected === 'BUSINESS_ACTIONABLE') return applied === 'BUSINESS_ACTIONABLE';
  if (expected === 'NOT_BUSINESS') return applied === 'NON_ACTIONABLE' || applied === 'PRIVATE_PERSONAL';
  if (expected === 'REVIEW') return applied === 'UNKNOWN_REQUIRES_REVIEW';
  return applied === 'NON_ACTIONABLE' || applied === 'PRIVATE_PERSONAL' || applied === 'UNKNOWN_REQUIRES_REVIEW';
}

async function main(): Promise<void> {
  const slug = process.argv[2];
  if (!slug) throw new Error('Usage: ts-node scripts/run-triage-evaluation.ts <tenant-slug> [report.json]');
  const catalogue = JSON.parse(readFileSync(join(__dirname, '../../../fixtures/evaluation/triage-catalogue.json'), 'utf8')) as { cases: CatalogueCase[] };

  const app = await NestFactory.createApplicationContext(AppModule, { logger: ['error'] });
  try {
    const tenant = await app.get(PrismaService).withRlsBypass((tx) => tx.tenant.findUnique({ where: { slug }, select: { id: true } }));
    if (!tenant) throw new Error(`Tenant "${slug}" not found.`);
    const env = app.get<OrbitEnv>(ORBIT_ENV);
    const triage = app.get(SemanticTriageService);
    const rows: Array<Record<string, unknown>> = [];

    for (const c of catalogue.cases) {
      const outcome = await triage.triage(tenant.id, undefined, {
        tenantId: tenant.id,
        channel: 'SIMULATED',
        provider: 'evaluation',
        externalEventId: `eval-${c.id}`,
        occurredAt: new Date(),
        sender: { address: c.from },
        recipients: [{ address: 'info@musterwerk.example' }],
        subject: c.subject,
        content: c.body,
        direction: 'INBOUND',
        hints: c.hints,
      });
      if (outcome.status !== 'DECIDED') {
        rows.push({ id: c.id, label: c.label, status: outcome.status, detail: outcome.detail, pass: false });
        continue;
      }
      const applied = deriveAppliedRelevance(outcome.result, { minConfidence: env.TRIAGE_MIN_CONFIDENCE, exclusionMinConfidence: env.TRIAGE_EXCLUSION_MIN_CONFIDENCE });
      const checks = {
        relevance: relevanceOk(applied.relevance, c.expect.relevance),
        category: !c.expect.categories || c.expect.categories.includes(outcome.result.category),
        flags: !c.expect.flags || c.expect.flags.every((f) => outcome.result.riskFlags.includes(f)),
        multipleIntents: c.expect.multipleIntents === undefined || (outcome.result.intents.length > 1) === c.expect.multipleIntents,
      };
      rows.push({
        id: c.id,
        label: c.label,
        category: outcome.result.category,
        applied: applied.relevance,
        confidence: outcome.result.confidence,
        riskFlags: outcome.result.riskFlags,
        intents: outcome.result.intents.map((i) => i.key),
        execution: `${outcome.execution.mode} ${outcome.execution.provider}/${outcome.execution.model} ${outcome.execution.promptVersion} ${outcome.execution.latencyMs}ms`,
        checks,
        pass: Object.values(checks).every(Boolean),
      });
    }

    for (const r of rows) console.log(`${r.pass ? 'PASS' : 'FAIL'}  ${String(r.id).padEnd(5)} ${String(r.label).padEnd(48)} → ${String(r.category ?? r.status).padEnd(24)} ${String(r.applied ?? '')}`);
    const passed = rows.filter((r) => r.pass).length;
    console.log(`\n${passed}/${rows.length} Fälle entsprechen der Erwartung.`);
    if (process.argv[3]) writeFileSync(process.argv[3], JSON.stringify({ generatedAt: new Date().toISOString(), passed, total: rows.length, rows }, null, 2));
  } finally {
    await app.close();
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
