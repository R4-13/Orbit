import { randomUUID } from 'node:crypto';
import type { INestApplication } from '@nestjs/common';
import { IntakeService } from '../src/intake/intake.service';
import type { NormalizedIntakeEvent } from '../src/intake/channel-event.types';
import { PrismaService } from '../src/prisma/prisma.service';
import { TenantsService } from '../src/tenants/tenants.service';
import { bootstrapE2eApp } from './utils/bootstrap-e2e-app';

/**
 * Funktionsnachweis 23.10., Grenze „Gmail-Rückstand nach Unterbrechung“: Was passiert, wenn die Aufnahme einer Nachricht mittendrin abbricht? Keine doppelten Wirkungen, nichts geht verloren.
 * (Der Fortschritt des Abrufs selbst ist in `gmail-poll.adapter.spec.ts` bewiesen; hier die Aufnahme gegen die echte Datenbank.)
 */
describe('Intake resilience (e2e)', () => {
  let app: INestApplication;
  let prisma: PrismaService;
  let intake: IntakeService;
  let tenantsService: TenantsService;
  const tenants: string[] = [];

  async function newTenant() {
    const suffix = randomUUID();
    const { tenant } = await tenantsService.bootstrapTenant({
      name: `E2E Resilience ${suffix}`,
      slug: `e2e-resilience-${suffix}`,
      adminEmail: `admin-${suffix}@e2e-resilience.example`,
      adminPassword: 'Musterwerk#2026!',
      adminFirstName: 'E2E',
      adminLastName: 'Admin',
    });
    tenants.push(tenant.id);
    return tenant.id;
  }

  function gmailEvent(tenantId: string, overrides: Partial<NormalizedIntakeEvent> = {}): NormalizedIntakeEvent {
    return {
      tenantId,
      channel: 'EMAIL',
      provider: 'gmail',
      externalEventId: `gm-${randomUUID()}`,
      occurredAt: new Date(),
      sender: { address: `kunde-${randomUUID()}@e2e.example` },
      recipients: [{ address: 'betrieb@e2e.example' }],
      subject: 'Frage zu Ihren Leistungen',
      content: 'Guten Tag, machen Sie auch Badsanierungen?',
      attachments: [],
      direction: 'INBOUND',
      ...overrides,
    };
  }

  beforeAll(async () => {
    app = await bootstrapE2eApp();
    prisma = app.get(PrismaService);
    intake = app.get(IntakeService);
    tenantsService = app.get(TenantsService);
  });

  afterAll(async () => {
    for (const tenantId of tenants) await prisma.withRlsBypass((tx) => tx.tenant.delete({ where: { id: tenantId } })).catch(() => undefined);
    await app.close();
  });

  it('eine bereits gespeicherte, nie zu Ende aufgenommene Nachricht (Absturz nach dem Speichern) wird weiterverwendet statt ein zweites Mal angelegt', async () => {
    const tenantId = await newTenant();
    const event = gmailEvent(tenantId);
    const scoped = prisma.forTenantId(tenantId);
    // Zustand nach dem Absturz: die Nachricht ist gespeichert, ein Eingang existiert noch nicht.
    await scoped.emailMessage.create({
      data: { tenantId, direction: 'INBOUND', fromAddress: event.sender!.address!, toAddresses: ['betrieb@e2e.example'], subject: event.subject, bodyText: event.content ?? '', providerMessageId: event.externalEventId, receivedAt: event.occurredAt },
    });

    const result = await intake.handleIntakeEvent(tenantId, undefined, event);

    expect(result.intakeEventId).toBeTruthy();
    expect(await scoped.emailMessage.count({ where: { providerMessageId: event.externalEventId } })).toBe(1); // nicht doppelt
    expect(await scoped.intakeEvent.count({ where: { provider: 'gmail', externalEventId: event.externalEventId } })).toBe(1);
  });

  it('dieselbe Nachricht ein zweites Mal aufzunehmen erzeugt weder einen zweiten Eingang noch einen zweiten Vorgang', async () => {
    const tenantId = await newTenant();
    const event = gmailEvent(tenantId);
    await intake.handleIntakeEvent(tenantId, undefined, event);
    const scoped = prisma.forTenantId(tenantId);
    const cases = await scoped.case.count();

    await expect(intake.handleIntakeEvent(tenantId, undefined, event)).rejects.toBeDefined(); // eindeutige Eingangs-Kennung hält

    expect(await scoped.intakeEvent.count({ where: { provider: 'gmail', externalEventId: event.externalEventId } })).toBe(1);
    expect(await scoped.case.count()).toBe(cases);
    expect(await scoped.emailMessage.count({ where: { providerMessageId: event.externalEventId } })).toBe(1);
  });

  it('ein hängengebliebener Eingang (aufgenommen, nie weiterverarbeitet) wird aus dem Gespeicherten weiterverarbeitet – genau einmal, mit gemerkter Richtung und Hinweisen', async () => {
    const tenantId = await newTenant();
    const scoped = prisma.forTenantId(tenantId);
    const event = gmailEvent(tenantId, { hints: { autoGenerated: true, bulk: false, providerSpam: false } });
    const message = await scoped.emailMessage.create({
      data: { tenantId, direction: 'INBOUND', fromAddress: event.sender!.address!, toAddresses: ['betrieb@e2e.example'], subject: event.subject, bodyText: event.content ?? '', providerMessageId: event.externalEventId, receivedAt: event.occurredAt },
    });
    const stranded = await scoped.intakeEvent.create({
      data: {
        tenantId,
        channel: 'EMAIL',
        provider: 'gmail',
        externalEventId: event.externalEventId,
        occurredAt: event.occurredAt,
        senderRef: event.sender as object,
        recipientRefs: event.recipients as object,
        subject: event.subject,
        emailMessageId: message.id,
        documentIds: [],
        status: 'RECEIVED',
        metadata: { hints: event.hints } as object,
      },
    });

    const first = await intake.resumeStranded(tenantId, stranded.id);

    expect(first).not.toBeNull();
    const after = await scoped.intakeEvent.findUniqueOrThrow({ where: { id: stranded.id }, include: { decision: true } });
    expect(after.decision).not.toBeNull(); // weiterverarbeitet
    expect(after.status).toBe('SKIPPED_NON_ACTIONABLE'); // der gemerkte Hinweis „automatisch erzeugt“ wurde beachtet, nicht als Kundenanfrage behandelt
    expect(await intake.resumeStranded(tenantId, stranded.id)).toBeNull(); // ein zweites Mal wirkt nichts mehr
  });

  it('ein Eingang mit Vorgang oder Entscheidung wird nie als hängengeblieben wieder aufgenommen', async () => {
    const tenantId = await newTenant();
    const done = await intake.handleIntakeEvent(tenantId, undefined, gmailEvent(tenantId));
    expect(await intake.resumeStranded(tenantId, done.intakeEventId)).toBeNull();
  });
});
